import type { ReactNode } from "react";

// Страничный заголовок: h1, подзаголовок и локальная навигация внутри лица.
//
// Отделён от тулбара намеренно. До 2026-09-10 всё это жило в одном `SiteHeader`, и из-за
// этого шапка была у двух страниц из семи: она требовала сессию, домен и обращение к базе,
// а `/zapis`, `/dannye`, `/kabinet`, `/poezdki` и `/t/[lookup]` рисовали каждая свою.
// Теперь глобальное (вордмарк, плашки сервисов, профиль) живёт в тулбаре общего layout, а
// здесь остаётся только то, что у каждой страницы своё, — и этот компонент синхронный: ни
// сессии, ни домена, ни запроса к базе.

export default function PageHead({
  title,
  sub,
  children,
}: {
  title: string;
  /** Одна строка под заголовком. Может быть разметкой: в неё вставляют ссылки. */
  sub?: ReactNode;
  /** Локальные ссылки страницы: «Справочник номеров», «← к карте», «весь город». */
  children?: ReactNode;
}) {
  return (
    <header className="page-header">
      <h1>{title}</h1>
      {sub && <p className="page-sub">{sub}</p>}
      {children && (
        // Вторая навигация на странице обязана отличаться именем от той, что в тулбаре, —
        // иначе скринридер объявит две одинаковые «навигации» и человек не поймёт, в какой он.
        <nav className="page-nav" aria-label="Разделы">
          {children}
        </nav>
      )}
    </header>
  );
}
