#!/usr/bin/env bash
# Проба прода: только чтение, ничего не меняет. Выполняется НА СЕРВЕРЕ, через ssh на
# stdin — как и остальные удалённые скрипты (мандат D-046: текст внутри команды проходит
# до четырёх парсеров и ломается на любом из них, файл — ноль).
#
# Зачем она есть. Смоук выкатки отвечает на вопрос «релиз поднялся?» и идёт только при
# выкатке. Между выкатками прод не проверяет никто, а есть поломки, которые именно так и
# устроены — тихие, накапливающиеся, замечаемые пользователем:
#
#   * схема прода расходится с кодом ([G231]: коллекция без своей колонки в служебной
#     `payload_locked_documents_rels` роняет админку целиком, у соседнего проекта она
#     пролежала так сутки). Гейты этого класса не видят по построению: заготовка DDL
#     снимается по именам НОВЫХ таблиц, `CREATE TABLE IF NOT EXISTS` на существующую
#     служебную — тихий no-op, список таблиц не меняется;
#   * регламент трасс перестал ходить — и сроки хранения тихо не исполняются (M0.A §3.4
#     требует алерта на отсутствие строки аудита за 25 часов, но читать журнал systemd
#     некому: ни почты, ни мониторинга в проекте нет);
#   * кончается запас партиций — приём точек упадёт у человека, который уже едет;
#   * сертификат домена не продлился — сайт умрёт целиком, и узнают об этом от людей;
#   * в `payload_migrations` появилась строка `dev` — следующая же выкатка повесит старт
#     службы вопросом «data loss will occur… (y/N)», а отвечать под systemd некому.
#
# Падение этого прогона и ЕСТЬ алерт: GitHub присылает письмо о красном расписании.
# Поэтому здесь нет «предупреждений», которые никого не будят: проверка либо падает,
# либо молчит. Мягкий порог допустим только там, где есть запас времени на реакцию.
#
# Что проверяется:
#   1. дрейф схемы: на каждую коллекцию Payload — своя колонка в locked_documents_rels;
#   2. регламент трасс: свежесть последнего успешного прогона и отказы за сутки;
#   3. запас партиций приёма точек;
#   4. отсутствие строки `dev` в payload_migrations;
#   5. выход из единого входа: наш роут → `end_session` ЕСА → возврат к нам;
#   6. срок сертификатов публичных доменов.
#
# Список коллекций и адреса приходят АРГУМЕНТАМИ: источник истины — конфиг Payload и
# секрет выкатки, второго экземпляра этого знания в скрипте быть не должно.
#
# В лог не печатается ничего об устройстве сервера — репозиторий публичен, а логи
# прогонов публичного репозитория публичны (AGENTS.md, «recon-поверхность»). Домены в
# метках заменены номерами, как в смоуке; имена коллекций и колонок к инфраструктуре не
# относятся — они и так лежат в коде.
#
# Аргументы: <каталог приложения> <локальный порт> <слаги коллекций через запятую>
#            [<публичный URL> ...]

set -euo pipefail

APP_DIR="${1:?не задан каталог приложения}"
PORT="${2:?не задан порт}"
SLUGS="${3:?не задан список коллекций}"
shift 3

# Пороги. Первые три — из M0.A §3.4 и планировщика (lib/track-scheduler.ts), чтобы проба и
# приложение считали поломкой одно и то же.
STALE_ALERT_HOURS=25
RUNWAY_ALERT_DAYS=3
# «Возраст самой старой партиции ≤ 30 суток плюс ширина партиции» (M0.A §3.4): срок сырья
# 30 суток (RAW_RETENTION_DAYS), партиции недельные (PARTITION_DAYS в
# lib/track-maintenance.ts). Ширина названа отдельно, чтобы в запросе не стояло голое «7».
PARTITION_WIDTH_DAYS=7
OLDEST_ALERT_DAYS=37
# Сертификат: у Let's Encrypt срок 90 дней и продление обычно за 30. Десять дней — это
# запас на «панель хостера не продлила, надо руками», а не «скоро истечёт».
CERT_ALERT_DAYS=10

ENV_FILE="$APP_DIR/shared/.env"
test -f "$ENV_FILE" || { echo "проба: нет файла окружения"; exit 1; }

# Значение может содержать «=» (пароль в URI), поэтому режется только первый знак.
DATABASE_URI=$(sed -n 's/^DATABASE_URI=//p' "$ENV_FILE" | head -n 1)
DATABASE_URI="${DATABASE_URI%\"}"
DATABASE_URI="${DATABASE_URI#\"}"
test -n "$DATABASE_URI" || { echo "проба: в окружении нет DATABASE_URI"; exit 1; }

# Клиент выбирается по факту наличия: psql на боксе может не стоять (база живёт своей
# жизнью), зато рядом всегда лежит выкаченный релиз с `pg` из зависимостей Payload.
if command -v psql >/dev/null 2>&1; then
  CLIENT=psql
else
  CLIENT=node
fi

# Одна точка выполнения запроса на весь скрипт: формат вывода у обоих клиентов одинаков
# (значения через «|», строки через перевод), иначе проверки разъехались бы по клиентам.
run_sql() {
  local query="$1" out rc=0
  # Код возврата клиента проверяется явно: при `set -e` неудачный запрос внутри подстановки
  # убил бы прогон молча. Текст ошибки наружу НЕ идёт — клиент печатает в него адрес сервера
  # базы, а лог публичный (AGENTS.md, «recon-поверхность»); достаточно кода.
  if [ "$CLIENT" = "psql" ]; then
    out=$(PGCONNECT_TIMEOUT=10 psql "$DATABASE_URI" -Atqc "$query" 2>/dev/null) || rc=$?
  else
    # `node -e` — всегда CommonJS, поэтому require здесь законен; каталог релиза даёт
    # доступ к `pg` из трассированных зависимостей Payload.
    out=$(cd "$APP_DIR/current" && DATABASE_URI="$DATABASE_URI" SQL="$query" node -e '
      const { Client } = require("pg");
      const c = new Client({ connectionString: process.env.DATABASE_URI });
      c.connect()
        .then(() => c.query(process.env.SQL))
        .then((r) => {
          const out = r.rows
            .map((row) => Object.values(row).map((v) => (v === null ? "" : v)).join("|"))
            .join(String.fromCharCode(10));
          if (out) console.log(out);
        })
        .catch(() => { process.exit(1); })
        .finally(() => c.end());
    ' 2>/dev/null) || rc=$?
  fi
  if [ "$rc" != "0" ]; then
    echo "проба: запрос к базе не прошёл (код $rc); текст ошибки в публичный лог не печатаем"
    exit 1
  fi
  echo "$out"
}

# Диагностика уходит в stdout, а НЕ в stderr, и это не косметика: вызывающий workflow
# глушит stderr ssh целиком, потому что клиент ssh печатает туда имя хоста и порт, а логи
# публичного репозитория публичны (AGENTS.md, «recon-поверхность»). Писали бы сюда — свои
# же сообщения о поломке исчезли бы вместе с чужими.
fail() { echo "$1"; exit 1; }

# ── 1. Дрейф схемы: колонки locked_documents_rels против списка коллекций ──────────────

COLUMNS_SQL="SELECT column_name FROM information_schema.columns
             WHERE table_name = 'payload_locked_documents_rels' ORDER BY column_name;"

# Каких колонок под коллекции не хватает в переданном списке. Вынесено в функцию, потому
# что спрашивать приходится дважды — см. ниже, зачем.
missing_columns() {
  local cols="$1" slug column out=""
  for slug in ${SLUGS//,/ }; do
    # Payload переводит слаг в имя колонки через snake_case: дефисы становятся
    # подчёркиваниями (`my-thing` → `my_thing_id`).
    column="${slug//-/_}_id"
    echo "$cols" | grep -qx "$column" || out="$out $slug"
  done
  echo "$out"
}

COLUMNS=$(run_sql "$COLUMNS_SQL")
test -n "$COLUMNS" || fail "проба: таблицы payload_locked_documents_rels нет вовсе"

count=$(echo "$SLUGS" | tr ',' '\n' | grep -c .)
missing=$(missing_columns "$COLUMNS")

# ⚠️ Прежде чем объявить дрейф — переспрашиваем. 2026-09-04 прогон отчитался «нет колонки
# entries_id», а следующий через несколько минут показал её на месте: схема не менялась и
# выкаток между прогонами не было, то есть первый ответ был неполным. Причину поймать не
# удалось, но реакция от неё не зависит: дрейф схемы — состояние СТОЙКОЕ, он не рассосётся
# за три секунды, а вот случайно неполный ответ рассосётся. Алерт, который иногда врёт,
# перестают читать целиком — это дороже, чем лишний запрос.
if [ -n "$missing" ]; then
  sleep 3
  COLUMNS=$(run_sql "$COLUMNS_SQL")
  missing=$(missing_columns "$COLUMNS")
  if [ -n "$missing" ]; then
    echo "дрейф схемы: в payload_locked_documents_rels нет колонок под коллекции:$missing"
    echo "получено колонок: $(echo "$COLUMNS" | tr '\n' ' ')"
    fail "лечится ALTER TABLE … ADD COLUMN IF NOT EXISTS \"<коллекция>_id\" integer + FK + индекс (G35)"
  fi
  echo "  схема      первый ответ был неполным, повтор чист — дрейфа нет"
fi

# Колонки на коллекции — это всё, что не служебная четвёрка самой таблицы.
have=$(echo "$COLUMNS" | grep -vxE 'id|order|parent_id|path' | grep -c '_id$' || true)
echo "  схема      колонок $have = коллекций $count, чисто"

# ── 2. Регламент трасс: ходит ли расписание ───────────────────────────────────────────
#
# M0.A §3.4: «отсутствие строки аудита за 25 часов — алерт; отказ процедуры должен быть
# громким». Громким он и был — в журнале systemd, которого никто не читает. Здесь он
# становится красным прогоном.

READY=$(run_sql "SELECT to_regclass('track.maintenance_run') IS NOT NULL;")
if [ "$READY" != "t" ] && [ "$READY" != "true" ]; then
  # Не поломка: схемы трасс может не быть вовсе. Но сказать вслух надо, иначе зелёный
  # прогон означал бы «проверка выполнялась».
  echo "  регламент  схемы трасс нет — проверка неприменима"
else
  BEHIND=$(run_sql "SELECT round(EXTRACT(EPOCH FROM (now() - max(started_at))) / 3600, 1)
                    FROM track.maintenance_run WHERE job = 'ensure_partitions' AND ok;")
  test -n "$BEHIND" || fail "регламент: ни одного успешного прогона в журнале — расписание не работало ни разу"
  # Сравнение дробных часов — awk: bash умеет только целые.
  awk -v b="$BEHIND" -v lim="$STALE_ALERT_HOURS" 'BEGIN { exit (b > lim) ? 1 : 0 }' \
    || fail "регламент: последний успешный прогон был $BEHIND ч назад (порог $STALE_ALERT_HOURS ч) — сроки хранения не исполняются"

  FAILED=$(run_sql "SELECT count(*) || '|' || coalesce(string_agg(DISTINCT job, ','), '')
                    FROM track.maintenance_run
                    WHERE NOT ok AND started_at > now() - interval '$STALE_ALERT_HOURS hours';")
  fails="${FAILED%%|*}"
  jobs="${FAILED#*|}"
  test "$fails" = "0" || fail "регламент: за сутки $fails отказ(ов) процедур: $jobs"
  echo "  регламент  последний успешный прогон $BEHIND ч назад, отказов нет"

  # ── 3. Запас партиций приёма точек ──────────────────────────────────────────────────
  #
  # Партиции недельные, имя = дата начала недели (lib/track-maintenance.ts). Запас — до
  # конца самой поздней. Без партиции вставка падает жёстко: «для строки не найдена
  # секция», то есть приём точек встаёт у человека, который уже едет.
  # Схема в запросе указана явно (`nspname = 'track'`), как и в самом приложении
  # (`partitionRunwayDays`): без неё запрос нашёл бы любую партиционированную таблицу с
  # именем `point` в чужой схеме — а на этом боксе живут соседи.
  PARTS=$(run_sql "SELECT max(to_date(right(c.relname, 8), 'YYYYMMDD')) + $PARTITION_WIDTH_DAYS - current_date
                     || '|' ||
                   (current_date - min(to_date(right(c.relname, 8), 'YYYYMMDD')))
                   FROM pg_class c
                   JOIN pg_inherits i ON i.inhrelid = c.oid
                   JOIN pg_class p ON p.oid = i.inhparent
                   JOIN pg_namespace n ON n.oid = p.relnamespace
                   WHERE n.nspname = 'track' AND p.relname = 'point'
                     AND c.relname ~ '^point_[0-9]{8}\$';")
  RUNWAY="${PARTS%%|*}"
  OLDEST="${PARTS#*|}"

  # ⚠️ Пустой ответ здесь — НЕ «база ещё не размечена», и мягкой строкой это быть не может.
  # Сюда доходят только после подтверждённого успешного `ensure_partitions` не старше 25
  # часов, а он создаёт партиции от начала недели на две вперёд — то есть минимум три.
  # Пусто значит либо их удалили руками, либо таблица переименована или уехала из схемы, и
  # тогда планировщик замолчал навсегда (`schemaReady()` вернёт false и он даже не
  # ругается), последняя успешная строка ещё сутки выглядит свежей, приложение отвечает —
  # и приём точек мёртв при зелёной пробе. Ровно та ложная зелень, ради которой проба и
  # заведена.
  test -n "$RUNWAY" && test "$RUNWAY" != "|" \
    || fail "партиции: у track.point не найдено ни одной партиции при свежем успешном прогоне регламента — приём точек не работает"

  test "$RUNWAY" -ge "$RUNWAY_ALERT_DAYS" \
    || fail "партиции: запас $RUNWAY суток (порог $RUNWAY_ALERT_DAYS) — приём точек скоро начнёт падать"

  # Вторая половина того же требования и куда важнее первой: M0.A §3.4 просит ежедневно
  # проверять, что возраст САМОЙ СТАРОЙ партиции ≤ 30 суток плюс её ширина. Запас вперёд
  # говорит, что приём не встанет; возраст назад — что срок хранения действительно
  # исполняется. Партиция, пережившая свой срок, — это персональные данные, которые мы
  # обещали стереть и не стёрли, и молчать об этом нельзя.
  test -n "$OLDEST" || fail "партиции: запас $RUNWAY суток, но возраст старейшей не прочитан"
  test "$OLDEST" -le "$OLDEST_ALERT_DAYS" \
    || fail "ретеншн: самой старой партиции $OLDEST суток (порог $OLDEST_ALERT_DAYS) — сырьё пережило свой срок, удаление по возрасту не отработало"
  echo "  партиции   запас $RUNWAY суток, старейшей $OLDEST суток (порог $OLDEST_ALERT_DAYS)"
fi

# ── 4. Строка `dev` в payload_migrations ──────────────────────────────────────────────
#
# Появляется от `next dev` против этой базы. Сама по себе тиха, но следующая выкатка с
# миграцией повесит старт службы вопросом «data loss will occur… (y/N)» — под systemd
# отвечать некому, и сайт не поднимется (docs/DEPLOY.md).

DEVROW=$(run_sql "SELECT count(*) FROM payload_migrations WHERE name = 'dev';")
test "$DEVROW" = "0" \
  || fail "миграции: в payload_migrations есть строка dev — следующая выкатка с миграцией повесит старт службы"
echo "  миграции   строки dev нет"

# ── 5. Выход из единого входа ─────────────────────────────────────────────────────────
#
# Проверяется весь наш конец цепочки: роут отвечает редиректом на `end_session` ЕСА с
# адресом возврата, и ЕСА этот адрес принимает (иначе он вернул бы человека на свою
# страницу входа, а не к нам). Запрос идёт с бокса: до российских хостов раннер GitHub
# не достаёт, как и в смоуке.

# ⚠️ При любом сетевом отказе curl печатает `000`, а НЕ пустую строку — проверено на
# соединении с закрытым портом и на таймауте. Поэтому «нет ответа» здесь всегда `000`, и
# ветки, написанные на проверку пустоты, были бы мертвы: недоступность чужой службы валила
# бы весь суточный прогон, да ещё и с сообщением, отправляющим чинить не туда. Нашло
# состязательное ревью, подтверждено опытом.
#
# Запас по времени — 30 с: при недоступном ЕСА роут сначала ждёт discovery (до 10 с) и
# только потом отвечает.
LOGOUT=$(curl -sS -o /dev/null -w '%{http_code} %{redirect_url}' --max-time 30 \
         -X POST "http://127.0.0.1:$PORT/api/auth/logout" 2>/dev/null || true)
code="${LOGOUT%% *}"
away="${LOGOUT#* }"

if [ "$code" = "000" ]; then
  # Роут не ответил. Причин две, и они требуют разной реакции, поэтому спрашиваем главную:
  # если служба отвечает — молчал именно выход (ждёт чужой discovery), и падать из-за
  # чужой сети нельзя; если не отвечает и она — лежит вся служба, и это громкая поломка,
  # которую между выкатками иначе не заметит никто.
  alive=$(curl -sS -o /dev/null -w '%{http_code}' --max-time 10 "http://127.0.0.1:$PORT/" 2>/dev/null || true)
  test "$alive" = "200" \
    || fail "приложение не ответило по локальному порту (главная: $alive) — служба лежит?"
  echo "  выход      роут не ответил за 30 с, главная жива — похоже, ЕСА недоступен и discovery ждёт таймаута"
else
  test "$code" = "303" || fail "выход: роут ответил $code, ожидалось 303"

  case "$away" in
    *"/oidc/logout"*)
      esa=$(curl -sS -o /dev/null -w '%{http_code} %{redirect_url}' --max-time 20 "$away" 2>/dev/null || true)
      esa_code="${esa%% *}"
      esa_back="${esa#* }"
      case "$esa_code" in
        302|303) echo "  выход      роут $code → end_session, ЕСА $esa_code → $esa_back" ;;
        # `000` — ЕСА не ответил; `200` — по стандарту он вправе показать страницу
        # подтверждения выхода (мы не шлём `id_token_hint`). Ни то, ни другое не поломка
        # НАШЕЙ стороны, а красное от чужой службы каждые сутки научило бы не смотреть на
        # красный цвет вовсе.
        000) echo "  выход      роут $code → end_session, но ЕСА не ответил (чужая служба, свой выход работает)" ;;
        200) echo "  выход      роут $code → end_session, ЕСА 200 (страница подтверждения — стандартом разрешено)" ;;
        *) fail "выход: ЕСА ответил $esa_code на end_session, ожидался редирект" ;;
      esac ;;
    *)
      # Не поломка сама по себе: без OIDC_CLIENT_ID входа на боксе нет вовсе, и выход
      # честно ведёт на главную. Но сказать об этом надо вслух, иначе «зелено» будет
      # означать «проверка не выполнялась».
      echo "  выход      роут $code → $away (выхода в ЕСА нет: вход выключен или ЕСА молчит)" ;;
  esac
fi

# ── 6. Срок сертификатов ──────────────────────────────────────────────────────────────
#
# Сертификаты выпускаются из панели хостера, не certbot'ом (docs/DEPLOY.md): продление —
# чужой автомат, и его отказ виден только истёкшим сертификатом. Смоук проверяет
# валидность в момент выкатки; между выкатками — эта строка.

if [ "$#" -eq 0 ]; then
  echo "  серты      проверка пропущена: адреса не заданы"
elif ! command -v openssl >/dev/null 2>&1; then
  echo "  серты      openssl на боксе нет — проверка неприменима"
else
  n=0
  for url in "$@"; do
    n=$((n + 1))
    host="${url#*://}"
    host="${host%%/*}"
    case "$url" in https://*) ;; *) fail "серты $n — адрес не https" ;; esac

    # ⚠️ `|| true` здесь не украшение. При `set -e` и `pipefail` любой ненулевой код в
    # этом конвейере (а `openssl s_client` отдаёт его штатно, закрывая соединение) убивает
    # скрипт МОЛЧА — без строки, без причины, с общим кодом 1. Поймано на своей же
    # проверке: прогон обрывался ровно здесь и выглядел как «упало неизвестно что».
    end=$( { echo | openssl s_client -connect "$host:443" -servername "$host" 2>/dev/null \
             | openssl x509 -noout -enddate 2>/dev/null | cut -d= -f2; } || true )
    test -n "$end" || fail "серты $n — не удалось прочитать сертификат"

    until=$(date -d "$end" +%s 2>/dev/null || true)
    test -n "$until" || fail "серты $n — не разобрал дату «$end»"

    left=$(( (until - $(date +%s)) / 86400 ))
    test "$left" -ge "$CERT_ALERT_DAYS" \
      || fail "серты $n — осталось $left суток (порог $CERT_ALERT_DAYS): продление из панели хостера не сработало"
    echo "  серты $n    осталось $left суток"
  done
fi

echo "проба пройдена"
