#!/usr/bin/env bash
# Смоук выкаченного релиза. Выполняется НА СЕРВЕРЕ, через ssh на stdin.
#
# Две проверки, и обе с бокса — по разным причинам.
#
# 1. По локальному порту. Отвечает ровно на «релиз работает», не смешивая это с
#    вопросами про DNS, прокси и сертификат: красный прогон должен говорить, что
#    чинить, а не что «где-то сломалось».
#
# 2. По публичному адресу — тоже с бокса, а НЕ с раннера GitHub. Раннер стоит за
#    границей и до этого хоста просто не достучался: curl отдал таймаут за 30 с,
#    хотя сайт при этом работал. Проверка с раннера была бы вечно красной и
#    научила бы игнорировать красный цвет. С бокса тот же запрос проходит и
#    покрывает весь реальный путь пользователя: DNS, прокси хостера, сертификат,
#    nginx, приложение.
#
# Публичных адресов может быть НЕСКОЛЬКО: у «ПОЗВОНИ» матрёшка доменов
# (lib/sites.ts), и каждый новый домен добавляет ровно те две вещи, которые
# ломаются молча — запись в server_name nginx и сертификат в панели. Домен, не
# попавший в смоук, обнаруживается пользователем, а не прогоном. Список доменов
# в этом файле не хранится: он приходит аргументами, единственный источник
# истины — реестр в lib/sites.ts и секрет выкатки.
#
# Проверяется то, что уже ломалось при постройке: страница, поиск адреса (справочник
# читается по пути и в standalone включается явно), Range к карте (без него карта не
# работает вообще).
#
# ⚠️ Чего смоук НЕ проверяет и проверить не может: что карта НАРИСОВАЛАСЬ. Он видит
# файлы и типы, а рисование — это WebGL в браузере. Проверять карту глазами и только
# на выведенной вперёд вкладке: в скрытой не срабатывает requestAnimationFrame, и
# MapLibre навсегда остаётся с незагруженным стилем — серый прямоугольник без единой
# ошибки, неотличимый от настоящей поломки (docs/SESSION_HANDOFF.md).
#
# Аргументы: <локальный порт> <версия maplibre> [<публичный URL> ...]
#
# ⚠️ Диагностика печатается в stdout, а не в stderr: вызывающий workflow глушит stderr
# клиента ssh целиком, потому что тот при отказе печатает имя хоста и порт отдельными
# словами, а маскировка GitHub ловит только полное значение секрета (AGENTS.md, D-038).
# Писали бы сюда — свои же сообщения о поломке исчезли бы вместе с чужими.

set -euo pipefail

PORT="${1:?не задан порт}"
MAPLIBRE_VERSION="${2:?не задана версия maplibre}"
shift 2
BASE="http://127.0.0.1:$PORT"
TRIES=10

# Служба только что перезапущена — ждём подъёма, но не «спим наугад».
for i in $(seq 1 "$TRIES"); do
  if curl -fsS -o /dev/null --max-time 5 "$BASE/" 2>/dev/null; then
    break
  fi
  if [ "$i" = "$TRIES" ]; then
    echo "страница не ответила за $TRIES попыток"
    exit 1
  fi
  sleep 2
done

check() {
  local label="$1" base="$2"

  local code
  code=$(curl -sS -o /dev/null -w '%{http_code}' --max-time 20 "$base/")
  test "$code" = "200" || { echo "$label — страница: $code, ожидалось 200"; exit 1; }
  echo "  $label страница        200"

  # Прибрежная улица выбрана не случайно: она в той части города, которую срезал
  # ошибочный bbox первой редакции M0.B (§5). Неверно собранная вырезка тут и всплывёт.
  local hits
  hits=$(curl -sS --max-time 20 "$base/api/search?q=%D0%9F%D1%80%D0%B8%D0%B1%D1%80%D0%B5%D0%B6%D0%BD%D0%B0%D1%8F" | grep -c '"kind"' || true)
  test "$hits" -ge 1 || { echo "$label — поиск адреса ничего не вернул"; exit 1; }
  echo "  $label поиск адреса    найдено"

  local range
  range=$(curl -sS -o /dev/null -w '%{http_code}' --max-time 20 -r 0-16 "$base/map/malmyzh.pmtiles")
  test "$range" = "206" || { echo "$label — карта: $range, ожидалось 206"; exit 1; }
  echo "  $label карта (Range)   206"

  # Воркер MapLibre — проверяется ТИП, а не только код ответа. 2026-08-30 карта была
  # сломана у пользователей именно типом: nginx не знал расширения .mjs и отдавал
  # воркер как application/octet-stream, а модульный скрипт с не-JS типом браузер
  # исполнять отказывается. Смоук тогда был зелёным — он спрашивал «файл отдаётся?»,
  # а надо было «чем отдаётся?». Путь версионный (docs/DOMAINS.md, scripts/copy-map-worker.mjs),
  # поэтому версия приходит аргументом из CI, а не зашита здесь.
  local wtype
  wtype=$(curl -sS -o /dev/null -w '%{content_type}' --max-time 20 \
          "$base/map/maplibre/$MAPLIBRE_VERSION/maplibre-gl-worker.mjs")
  case "$wtype" in
    application/javascript*|text/javascript*)
      echo "  $label воркер карты    $wtype" ;;
    *)
      echo "$label — воркер MapLibre отдан как «$wtype», а нужен JS-тип: карта будет серой"
      exit 1 ;;
  esac

  # Справочник ходит в базу: 200 здесь значит «миграции применились и БД жива».
  local dir
  dir=$(curl -sS -o /dev/null -w '%{http_code}' --max-time 20 "$base/nomera")
  test "$dir" = "200" || { echo "$label — справочник: $dir, ожидалось 200"; exit 1; }
  echo "  $label справочник      200"
}

check "локально " "$BASE"

if [ "$#" -eq 0 ]; then
  echo "  публичная проверка пропущена: адрес не задан"
else
  n=0
  for url in "$@"; do
    n=$((n + 1))
    # Домены в метку не печатаются: публичный домен продукта секретом не является,
    # но и печатать в лог больше необходимого незачем — номера хватает, чтобы
    # понять, какой по счёту адрес из списка упал.
    check "публично $n" "$url"

    # Схема проверяется до сертификата, иначе проверка ниже — ложная зелень:
    # ssl_verify_result равен 0 и там, где TLS вообще не было, так что http-адрес
    # в списке отчитался бы «сертификат валиден».
    case "$url" in
      https://*) ;;
      *) echo "публично $n — адрес не https, сертификат непроверяем"; exit 1 ;;
    esac

    # Сертификат проверяется отдельно: истёкший или неверный серт даёт ошибку
    # соединения, а не плохой код ответа, и без явной проверки выглядел бы как
    # «сеть моргнула». У нового домена матрёшки это самая частая поломка: DNS уже
    # есть, приложение отвечает, а серт в панели ещё не выпущен (G153).
    tls=$(curl -sS -o /dev/null -w '%{ssl_verify_result}' --max-time 20 "$url/")
    test "$tls" = "0" || { echo "публично $n — сертификат не прошёл проверку ($tls)"; exit 1; }
    echo "  публично $n сертификат    валиден"
  done
fi

echo "смоук пройден"
