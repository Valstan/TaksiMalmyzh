#!/usr/bin/env bash
# Смоук выкаченного релиза. Выполняется НА СЕРВЕРЕ, через ssh на stdin.
#
# Две проверки, и обе с бокса — по разным причинам.
#
# 1. По локальному порту. Отвечает ровно на «релиз работает», не смешивая это с
#    вопросами про DNS, прокси и сертификат: красный прогон должен говорить, что
#    чинить, а не что «где-то сломалось».
#
# 2. По публичному адресу — тоже с бокса, а НЕ с раннера GitHub. Раннер стоит за
#    границей и до этого хоста просто не достучался: curl отдал таймаут за 30 с,
#    хотя сайт при этом работал. Проверка с раннера была бы вечно красной и
#    научила бы игнорировать красный цвет. С бокса тот же запрос проходит и
#    покрывает весь реальный путь пользователя: DNS, прокси хостера, сертификат,
#    nginx, приложение.
#
# Проверяется то, что уже ломалось при постройке: страница, поиск адреса (справочник
# читается по пути и в standalone включается явно), Range к карте (без него карта не
# работает вообще).
#
# Аргументы: <локальный порт> [<публичный адрес>] [<число попыток>]

set -euo pipefail

PORT="${1:?не задан порт}"
PUBLIC="${2:-}"
TRIES="${3:-10}"
BASE="http://127.0.0.1:$PORT"

# Служба только что перезапущена — ждём подъёма, но не «спим наугад».
for i in $(seq 1 "$TRIES"); do
  if curl -fsS -o /dev/null --max-time 5 "$BASE/" 2>/dev/null; then
    break
  fi
  if [ "$i" = "$TRIES" ]; then
    echo "страница не ответила за $TRIES попыток" >&2
    exit 1
  fi
  sleep 2
done

check() {
  local label="$1" base="$2"

  local code
  code=$(curl -sS -o /dev/null -w '%{http_code}' --max-time 20 "$base/")
  test "$code" = "200" || { echo "$label — страница: $code, ожидалось 200" >&2; exit 1; }
  echo "  $label страница        200"

  # Прибрежная улица выбрана не случайно: она в той части города, которую срезал
  # ошибочный bbox первой редакции M0.B. Неверно собранная вырезка тут и всплывёт.
  local hits
  hits=$(curl -sS --max-time 20 "$base/api/search?q=%D0%9F%D1%80%D0%B8%D0%B1%D1%80%D0%B5%D0%B6%D0%BD%D0%B0%D1%8F" | grep -c '"kind"' || true)
  test "$hits" -ge 1 || { echo "$label — поиск адреса ничего не вернул" >&2; exit 1; }
  echo "  $label поиск адреса    найдено"

  local range
  range=$(curl -sS -o /dev/null -w '%{http_code}' --max-time 20 -r 0-16 "$base/map/malmyzh.pmtiles")
  test "$range" = "206" || { echo "$label — карта: $range, ожидалось 206" >&2; exit 1; }
  echo "  $label карта (Range)   206"

  # Справочник ходит в базу: 200 здесь значит «миграции применились и БД жива».
  local dir
  dir=$(curl -sS -o /dev/null -w '%{http_code}' --max-time 20 "$base/nomera")
  test "$dir" = "200" || { echo "$label — справочник: $dir, ожидалось 200" >&2; exit 1; }
  echo "  $label справочник      200"
}

check "локально " "$BASE"

if [ -n "$PUBLIC" ]; then
  check "публично " "$PUBLIC"

  # Сертификат проверяется отдельно: истёкший или неверный серт даёт ошибку
  # соединения, а не плохой код ответа, и без явной проверки выглядел бы как
  # «сеть моргнула».
  tls=$(curl -sS -o /dev/null -w '%{ssl_verify_result}' --max-time 20 "$PUBLIC/")
  test "$tls" = "0" || { echo "публично — сертификат не прошёл проверку ($tls)" >&2; exit 1; }
  echo "  публично  сертификат     валиден"
else
  echo "  публичная проверка пропущена: адрес не задан"
fi

echo "смоук пройден"
