#!/usr/bin/env bash
# Смоук выкаченного релиза. Выполняется НА СЕРВЕРЕ, через ssh на stdin.
#
# Проверяет приложение напрямую по локальному порту, не через домен. Так смоук
# отвечает на вопрос «релиз работает?», а не на смесь вопросов «работает ли релиз,
# доехал ли DNS, выпущен ли сертификат» — а именно эта смесь и делает красный
# прогон бесполезным: непонятно, что чинить.
#
# Проверяются три вещи, и каждая из них уже ломалась при постройке:
#   страница        — что рантайм вообще поднялся;
#   поиск адреса    — что адресный справочник доехал (он читается по пути, и в
#                     standalone его надо включать явно — иначе поиск отвечает
#                     «адреса нет» на любой запрос);
#   Range к карте   — что вырезка на месте и статика отдаёт диапазоны байт, без
#                     чего карта не работает вообще.
#
# Аргументы: <локальный порт> [<число попыток>]

set -euo pipefail

PORT="${1:?не задан порт}"
TRIES="${2:-10}"
BASE="http://127.0.0.1:$PORT"

# Служба только что перезапущена — даём ей подняться, но не «спим наугад».
for i in $(seq 1 "$TRIES"); do
  if curl -fsS -o /dev/null --max-time 5 "$BASE/" 2>/dev/null; then
    break
  fi
  if [ "$i" = "$TRIES" ]; then
    echo "страница не ответила за $TRIES попыток" >&2
    exit 1
  fi
  sleep 2
done

code=$(curl -sS -o /dev/null -w '%{http_code}' --max-time 15 "$BASE/")
test "$code" = "200" || { echo "страница: $code, ожидалось 200" >&2; exit 1; }
echo "  страница        200"

# Прибрежная улица выбрана не случайно: она лежит в той части города, которую
# срезал ошибочный bbox первой редакции M0.B. Если вырезка снова собрана неверно,
# смоук это увидит.
hits=$(curl -sS --max-time 15 "$BASE/api/search?q=%D0%9F%D1%80%D0%B8%D0%B1%D1%80%D0%B5%D0%B6%D0%BD%D0%B0%D1%8F" | grep -c '"kind"' || true)
test "$hits" -ge 1 || { echo "поиск адреса ничего не вернул" >&2; exit 1; }
echo "  поиск адреса    найдено"

range=$(curl -sS -o /dev/null -w '%{http_code}' --max-time 15 -r 0-16 "$BASE/map/malmyzh.pmtiles")
test "$range" = "206" || { echo "карта: $range на Range-запрос, ожидалось 206" >&2; exit 1; }
echo "  карта (Range)   206"

echo "смоук пройден"
