#!/usr/bin/env bash
# Задать токен записи этапа A, введя его руками. Запускается НА СЕРВЕРЕ, под sudo.
#
# Зачем этот скрипт существует, хотя токен умеет генерироваться сам.
#
# Сгенерированный токен приходится где-то ПРОЧИТАТЬ, чтобы ввести его на телефоне, — и
# прочитанный секрет естественным движением попадает в переписку, в историю терминала, в
# буфер обмена. Так и случилось 2026-08-30: токен был напечатан в консоли и уехал в чат,
# после чего его пришлось менять.
#
# Токен, который владелец придумал сам и ввёл здесь, не показывается никому и никогда:
# ввод не отображается, в историю команд не попадает, наружу не выводится. Читать его
# больше не нужно — он уже известен тому единственному, кому положено.
#
# Запуск:
#   sudo bash deploy/set-etap-a-token.sh <файл токена> <имя службы>

set -euo pipefail

TOKEN_FILE="${1:?не задан файл токена}"
SERVICE="${2:?не задано имя службы}"

# ⚠️ Токен едет в заголовке Authorization, а заголовки по спецификации ByteString:
# кириллица делает запрос НЕВОЗМОЖНЫМ, а не «менее удобным» — клиент падает при сборке.
# В проекте, где кириллица повсюду, это ошибка, которую делаешь не задумываясь.
read -r -s -p "Токен (латиница, цифры, -_ ; не короче 16): " T1
echo
read -r -s -p "Ещё раз: " T2
echo

[ "$T1" = "$T2" ] || { echo "не совпадают" >&2; exit 1; }
[ ${#T1} -ge 16 ] || { echo "короче 16 символов — подбирается перебором" >&2; exit 1; }
printf '%s' "$T1" | LC_ALL=C grep -qE '^[A-Za-z0-9._~-]+$' \
  || { echo "только латиница, цифры и . _ ~ - : иначе запрос невозможно собрать" >&2; exit 1; }

install -d -o root -g root -m 700 "$(dirname "$TOKEN_FILE")"
printf '%s' "$T1" > "$TOKEN_FILE"
chown root:root "$TOKEN_FILE"
chmod 600 "$TOKEN_FILE"
echo "· токен записан (${#T1} символов)"

# Credential читается службой при СТАРТЕ, а не на каждом запросе: без рестарта служба
# продолжала бы принимать прежний токен, и смена была бы декорацией.
systemctl restart "$SERVICE"
sleep 4
systemctl is-active "$SERVICE" >/dev/null && echo "· служба перезапущена, новый токен действует" \
  || { echo "служба не поднялась" >&2; exit 1; }
