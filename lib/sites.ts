/** Корень матрёшки. Всё, что не опознано, показывается им. */
export const ROOT_SITE: Site = SITES[0];

/** Домен, на котором сервис фактически живёт сейчас (для абсолютных ссылок). */
export function canonicalSite(): Site {
  return ROOT_SITE.live ? ROOT_SITE : (SITES.find((s) => s.live) ?? ROOT_SITE);
}

// Реестр — данные, а опечатка в данных ломает тихо: неверный punycode просто
// никогда не совпадёт с `Host`, и домен молча покажет корень. Поэтому инварианты
// проверяются на импорте модуля: сборка (`next build`) импортирует его и падает
// на месте, а не отдаёт пользователю не тот сайт.
(function assertRegistry() {
  const seen = new Set<string>();
  for (const site of SITES) {
    if (site.host !== site.host.toLowerCase()) {
      throw new Error(`sites: хост должен быть в нижнем регистре: ${site.host}`);
    }
    // `Host` от браузера всегда ASCII; кириллица здесь означала бы, что запись
    // не сматчится никогда.
    if (!/^[a-z0-9.-]+$/.test(site.host)) {
      throw new Error(`sites: хост должен быть punycode/ASCII: ${site.host}`);
    }
    if (new URL(`http://${site.display}`).hostname !== site.host) {
      throw new Error(`sites: ${site.display} не соответствует ${site.host}`);
    }
    if (seen.has(site.host)) {
      throw new Error(`sites: дублирующийся хост ${site.host}`);
    }
    seen.add(site.host);
    if (site.kind === "category" && !site.categories?.length) {
      throw new Error(`sites: у категорийного домена ${site.id} нет категорий`);
    }
  }
})();

/**
 * Опознать сайт по заголовку `Host`.
 *
 * Незнакомый хост — корень: приложение доступно и по адресу, которого нет в
 * реестре (прямой запрос к боксу, новый домен до правки реестра), и вести себя
 * при этом должно как весь сервис, а не падать.
 */
export function resolveSite(hostHeader: string | null | undefined): Site {
  if (!hostHeader) return ROOT_SITE;

  // Отрезаем порт. IPv6 в `Host` пришёл бы в скобках — такому запросу в реестре
  // всё равно нечего искать, он уйдёт в корень.
  const host = hostHeader.trim().toLowerCase().split(":")[0];

  const exact = SITES.find((s) => s.host === host);
  if (exact) return exact;

  // Локальная разработка: `такси.localhost:3000` браузер резолвит в 127.0.0.1 и
  // отправляет первую метку в punycode — тем же, что и в реестре. Сопоставление
  // по метке нарочно ограничено `localhost`: на проде набор доменов задаёт
  // `server_name` nginx, и угадывать там нечего.
  if (host === "localhost" || host.endsWith(".localhost")) {
    const label = host.slice(0, -"localhost".length).replace(/\.$/, "");
    const byLabel = SITES.find((s) => s.host.split(".")[0] === label);
    if (byLabel) return byLabel;
  }

  return ROOT_SITE;
}

/**
 * Ссылка на страницу другого сайта матрёшки.
 *
 * На свой сайт — всегда относительная: она переживает и смену домена, и работу
 * через подменённый `Host`. На чужой живой — абсолютная. На чужой ещё не
 * заведённый — `fallback` в текущем домене: пока `позвони.вмалмыже.рф` не
 * существует, «весь справочник» обязан вести к справочнику, а не в ошибку DNS.
 */
export function siteHref(from: Site, to: Site, path: string, fallback: string): string {
  if (from.id === to.id) return path;
  if (!to.live) return fallback;
  return `https://${to.host}${path}`;
}

/** Категории, которые показывает домен. Для корня — все. */
export function siteCategories(site: Site): EntryCategory[] | null {
  return site.kind === "category" ? (site.categories ?? null) : null;
}
