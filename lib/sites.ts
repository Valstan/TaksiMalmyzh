// Матрёшка доменов «ПОЗВОНИ» — решение владельца 2026-08-30.
//
// Одно приложение показывает несколько лиц, и лицо выбирает заголовок `Host`.
// Корень — `позвони.вмалмыже.рф`, весь справочник города. Внутри него живут
// сервисы со своими поддоменами: `такси.вмалмыже.рф` — та же такси-категория,
// открытая отдельной дверью; дальше `услуги.`, `магазины.`, а внутри магазинов
// когда-нибудь отдельные бизнесы (`бригадир.`). Матрёшка, а не набор сайтов:
// содержимое одно, точек входа много.
//
// Почему не отдельные приложения на каждый домен: справочник однороден по
// анатомии (название — телефон — цены — рейтинг), и любая развилка «а как это
// на такси-сайте» немедленно стала бы двумя расходящимися копиями кода —
// класс #087, тот же, из-за которого канон запрещает копировать CLAUDE.md в
// vendor-файлы. Здесь развилка ровно одна и она — данные, а не код.
//
// ⚠️ Заводить новый домен = три действия, и только одно из них здесь:
//   1. запись DNS и сертификат в панели хостера — руками владельца;
//   2. домен в `server_name` секции nginx (`deploy/nginx.conf.example`);
//   3. запись в этом реестре с `live: true`.
// Пока `live: false`, приложение знает про домен, но не строит на него ссылок:
// ссылка на несуществующий поддомен — это ошибка у пользователя в браузере,
// а не «пока не доехало».

/** Категории справочника — значения совпадают с `collections/Entries.ts`. */
export type EntryCategory = "taxi" | "shop" | "master" | "brigade" | "cargo" | "other";

/**
 * Уровень матрёшки. `service` — весь «ПОЗВОНИ»; `category` — одна или несколько
 * категорий справочника; `business` — карточка одного бизнеса (спринт 8, когда
 * у бизнесов появятся кабинеты; здесь пока только тип, ни одного живого домена).
 */
export type SiteKind = "service" | "category" | "business";

export interface Site {
  /** Ключ реестра, он же используется в разметке и смоуке. */
  id: string;
  /**
   * Хост так, как он приходит в заголовке `Host`. Браузер отправляет IDN в
   * punycode, поэтому здесь punycode, а не кириллица: сравнение строк должно
   * быть тупым, без нормализации в рантайме.
   */
  host: string;
  /** Тот же хост человеку — в разметку и в документацию. */
  display: string;
  kind: SiteKind;
  /** Название сервиса: h1 и хлебные крошки. */
  title: string;
  /**
   * Заголовок вкладки. Отдельным полем, а не `${title} — Малмыж`: у
   * категорийных доменов город уже внутри названия, и правило дало бы
   * «ТАКСИ МАЛМЫЖ — Малмыж». Данные вместо догадки.
   */
  metaTitle: string;
  tagline: string;
  /** Для `kind: "category"` — какие категории справочника показывает домен. */
  categories?: EntryCategory[];
  /**
   * Домен заведён в DNS, с сертификатом, и на него можно ставить ссылки.
   * `false` — запись существует как план: скоуп работает (домен можно проверить
   * подменой `Host`), но абсолютных ссылок на него никто не построит.
   */
  live: boolean;
}

