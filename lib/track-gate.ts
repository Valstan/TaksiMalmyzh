// Гейт записи поездки.
//
// ⚠️ Зачем он существует. Стенд открыт наружу — решение владельца 2026-08-29. Если запись
// открыта вместе с ним, поездку сможет записать любой посторонний, а чужая трасса это
// персональные данные второго субъекта, то есть **этап B**, в который проект ещё не входил
// (M0.A §8.0). Открытая запись пересекала бы эту границу молча, без решения владельца.
//
// КАК ЭТО УСТРОЕНО ТЕПЕРЬ (2026-08-30, по просьбе владельца — «пусть ничего не вводит»):
//
// Никакого токена, который надо где-то прочитать и куда-то ввести, больше нет. Запись
// разрешена тому, кто ВОШЁЛ в приложение — обычной сессией Payload, той же, что и в админке.
// С 2026-09-02 аккаунт посетителя создаётся автоматически при входе через единый вход
// экосистемы, поэтому «вошедший» больше не значит «владелец» — гейт проверяет роль.
//
// Это не упрощение ради удобства, а устранение целого класса ошибок: у процедуры, в которой
// есть шаг «прочитай секрет глазами», рано или поздно этот секрет утекает — прочитанное
// показывают, копируют и вставляют, потому что иначе им нельзя воспользоваться. Так и
// случилось с прежним общим токеном 2026-08-30. Секрет, которого нет, не утекает.
//
// Мастер-выключатель остался: TRACK_RECORDING=on. Он отвечает на другой вопрос — не «кто
// это», а «открыт ли этап записи вообще», и выключается одной строкой, когда замеры
// закончены.

export type GateResult =
  | { ok: true; userId: number }
  | { ok: false; status: 404 | 401 };

/**
 * Пускать ли к записи.
 *
 * Выключенная запись отвечает **404, а не 403**: «такого адреса нет» не сообщает
 * постороннему, что здесь что-то есть и оно чем-то закрыто.
 */
export async function checkRecordingGate(request: Request): Promise<GateResult> {
  if (process.env.TRACK_RECORDING !== "on") return { ok: false, status: 404 };

  try {
    // Импорт динамический, а не в шапке файла: `@payload-config` — алиас сборщика, и
    // обычный node его не резолвит. Так модуль остаётся пригодным для проверок, где
    // Payload не поднимают, а выключатель выше отрабатывает раньше любого импорта.
    const { getPayload } = await import("payload");
    const { default: config } = await import("@payload-config");
    const payload = await getPayload({ config });
    const { user } = await payload.auth({ headers: request.headers });
    // С 2026-09-02 аккаунт может завести себе любой через единый вход — но этап A
    // остаётся этапом A: записывают только персонал. Посетителю — тот же 401, что
    // и гостю: «нужно войти» для него означает «нужно войти персоналом».
    if (!user || user.role !== "superadmin") return { ok: false, status: 401 };
    return { ok: true, userId: Number(user.id) };
  } catch {
    // Сломанная сессия — это «не вошёл», а не «ошибка сервера».
    return { ok: false, status: 401 };
  }
}
