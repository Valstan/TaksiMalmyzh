/** Номер счётчика. Не секрет: он и так стоит в HTML каждой страницы открытым текстом. */
export const METRIKA_ID = 112434794;

/** Хост, ради которого пришлось ослабить CSP. Одно место на код и на конфиг сборки. */
export const METRIKA_HOST = "https://mc.yandex.ru";

/**
 * Ставить ли счётчик на страницу.
 *
 * Выключается одной строкой `METRIKA=off` в окружении бокса — по образцу
 * `TRACK_RECORDING`. В разработке не ставится никогда: локальные заходы не должны
 * попадать в статистику владельца и портить ему замеры.
 */
export function metrikaEnabled(): boolean {
  return process.env.NODE_ENV === "production" && process.env.METRIKA !== "off";
}
