// Устойчивый ключ номера внутри карточки справочника.
//
// Единственный экземпляр нормализации в продукте: его зовут и карма, и комментарии, и
// ранжирование витрины. Две нормализации одного номера означали бы, что карма и
// комментарий на один телефон висят на разных ключах и связать их нечем.
//
// ⚠️ ПОЧЕМУ НЕ `entries_phones.id`, хотя он есть. Проверено по коду, а не по памяти:
//   • `migrations/20260829_193521_init.ts` — у `entries_phones` колонка `id varchar
//     PRIMARY KEY` БЕЗ DEFAULT: база этот id не порождает;
//   • Payload выдаёт его полем `baseIDField` с хуком `beforeChange: value || новый`, то
//     есть id сохраняется, ТОЛЬКО если приехал во входных данных, а при дублировании
//     карточки перевыпускается всегда;
//   • drizzle-адаптер при `update` сносит все строки массива у родителя и вставляет их
//     заново — строки телефонов физически пересоздаются при каждом сохранении карточки.
// Живое доказательство класса лежит в этом же репозитории: `updateOwnCard` в
// `lib/market.ts` шлёт `prices` без `id`, то есть каждое сохранение карточки владельцем
// перевыпускает id всех цен. Значит id строки массива — артефакт состояния формы, а не
// бизнес-ключ, и карма на нём обнулялась бы при правке карточки — причём не всегда, а
// через раз, самый неприятный вид отказа: «иногда пропадает».
//
// Модуль чистый: ни `pg`, ни `node:crypto`. Это позволяет звать его и из серверного
// компонента, и из клиентского; `lib/karma.ts` так не может — он тянет и то и другое.

/** Потолок длины ключа. Совпадает с CHECK в DDL. */
export const PHONE_KEY_MAX = 32;

/** Часовой «вся организация целиком». NULL в первичном ключе Postgres невозможен. */
export const ORG_KEY = "";

/**
 * Ключ номера. Идемпотентна: `phoneKey(phoneKey(x)) === phoneKey(x)` — клиент может
 * прислать уже нормализованное, сервер нормализует присланное ещё раз и не разъедется
 * сам с собой.
 *
 * ⚠️ Код города для коротких местных номеров НЕ угадывается: «2-22-22» остаётся `22222`.
 * Угадать неверно — значит склеить карму двух разных номеров; это хуже, чем не склеить
 * карму одного номера, записанного двумя способами.
 *
 * Пустая строка на выходе означает «это не номер» (в поле написали «нет», «по договору»).
 * У такого поля кармы нет: виджет под ним не рисуется, API отвечает отказом. Иначе оно
 * слилось бы с часовым организации.
 */
export function phoneKey(raw: string): string {
  const trimmed = String(raw ?? "").trim();
  const plus = trimmed.startsWith("+");
  const digits = trimmed.replace(/\D/g, "");

  if (digits.length === 0) return ORG_KEY;
  if (digits.length === 11 && (digits[0] === "7" || digits[0] === "8")) {
    return `+7${digits.slice(1)}`;
  }
  if (digits.length === 10) return `+7${digits}`;
  if (plus) return `+${digits}`.slice(0, PHONE_KEY_MAX);
  return digits.slice(0, PHONE_KEY_MAX);
}
